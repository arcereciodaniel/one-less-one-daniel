"use strict";
const {test}=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {JSDOM,VirtualConsole}=require("jsdom");
const html=fs.readFileSync("mobile-pilot/public/index.html","utf8");
const app=fs.readFileSync("mobile-pilot/public/app.js","utf8");
const helper=fs.readFileSync("mobile-pilot/public/split-fare.js","utf8");
test("iPhone: grupo hotel USD con Charlie de dos partes se envía en un solo registro",async()=>{
 const errors=[],vc=new VirtualConsole();
 vc.on("jsdomError",e=>errors.push(String(e.stack||e)));
 const dom=new JSDOM(html,{url:"https://mobile.example.workers.dev/",runScripts:"outside-only",virtualConsole:vc,pretendToBeVisual:true});
 const w=dom.window,root=w.document;
 w.localStorage.setItem("one_one_mobile_v1_key","m".repeat(40));
 Object.defineProperty(w.crypto,"randomUUID",{configurable:true,value:()=> "split-client-abcdefgh12345678"});
 const submitted=[];
 w.fetch=async(path,opts={})=>{
  if(path==="/api/catalog")return {ok:true,json:async()=>({catalog:{categories:[],debts:[],goals:[]}})};
  if(path==="/api/inbox"&&opts.method==="POST"){
   const entry=JSON.parse(opts.body);submitted.push(entry);
   return {ok:true,json:async()=>({id:entry.id,received:true})};
  }
  throw Error("Solicitud inesperada: "+path);
 };
 w.confirm=()=>true;
 w.eval(helper+"\n"+app);
 await new Promise(resolve=>setTimeout(resolve,10));
 root.querySelector('[data-type="Cobro"]').click();
 root.getElementById("amount").value="328";
 root.getElementById("currency").value="USD";
 root.getElementById("currency").dispatchEvent(new w.Event("change",{bubbles:true}));
 root.getElementById("splitToggle").checked=true;
 root.getElementById("splitToggle").dispatchEvent(new w.Event("change",{bubbles:true}));
 root.getElementById("splitGroupName").value="Hotel con amigos";
 root.getElementById("description").value="Reserva hotel";
 const first=root.querySelector("#splitRows .split-row");
 assert(first,"Debe mostrar una fila de cobro");
 first.querySelector(".split-person").value="Charlie";
 first.querySelector(".split-shares").value="2";
 root.getElementById("splitAdd").click();
 const rows=root.querySelectorAll("#splitRows .split-row");
 rows[1].querySelector(".split-person").value="Ana";
 rows[1].querySelector(".split-shares").value="1";
 root.getElementById("amount").dispatchEvent(new w.Event("input",{bubbles:true}));
 assert.match(root.getElementById("splitPreview").textContent,/\$164\.00/);
 root.getElementById("entryForm").dispatchEvent(new w.Event("submit",{bubbles:true,cancelable:true}));
 await new Promise(resolve=>setTimeout(resolve,20));
 assert.equal(submitted.length,1,"El reparto se envía como una transacción");
 const p=submitted[0].movement;
 assert.equal(p.type,"Cobro dividido");assert.equal(p.currency,"USD");assert.equal(p.groupName,"Hotel con amigos");
 assert.equal(p.amount,328);assert.equal(p.selfAmount,82);
 assert.equal(p.participants.length,2);
 assert.equal(p.participants[0].person,"Charlie");
 assert.equal(p.participants[0].amount,164);
 assert.equal(p.participants[1].amount,82);
 assert.equal(w.localStorage.getItem("one_one_mobile_v1_draft"),null);
 assert.match(root.getElementById("status").textContent,/Recibido/);
 assert.deepEqual(errors,[]);
 w.close();
});
